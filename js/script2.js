/*---------------------------------------------------------------
------ここから　トップへ戻るボタン処理------
---------------------------------------------------------------*/

// 要素を取得
const pageTopBtn = document.querySelector('#js-page-top');

// クリックイベントを設定
pageTopBtn.addEventListener('click', () => {
  window.scrollTo({
    top: 0,
    behavior: 'smooth' // スムーズにスクロールさせる
  });
});

